teks = "Algoritma"

# Menampilkan string asli
print("Teks asli:", teks)

# Menghitung panjang string menggunakan fungsi len()
print("Panjang string:", len(teks))

# Mengubah seluruh karakter menjadi huruf besar menggunakan method upper()
print("Huruf besar:", teks.upper())

# Mengubah seluruh karakter menjadi huruf kecil menggunakan method lower()
print("Huruf kecil:", teks.lower())